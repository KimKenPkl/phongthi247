'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const storage=new Map(),window={localStorage:{getItem:k=>storage.get(k)??null,setItem:(k,v)=>storage.set(k,String(v)),removeItem:k=>storage.delete(k)}};
vm.runInNewContext(fs.readFileSync('assets/lab-progress.js','utf8'),{window,Date,JSON,Number,Array,Map,Object,String});
const api=window.PTWLabProgress;
const first=api.record('nhiem-vu','reactor:water',{kind:'reactor',completedAt:Date.UTC(2026,10,23)});
assert.equal(first.completedAt,'2026-11-23T00:00:00.000Z');
assert.equal(api.record('nhiem-vu','reactor:water',{kind:'reactor',completedAt:Date.UTC(2026,10,23)}).eventId,first.eventId);
api.record('game','quiz',{best:80,lowerIsBetter:false});
storage.set('hh60s_chem_labs_v2',JSON.stringify({reactor:['water','water'],metal:['Fe_Cu']}));
storage.set('hh60s_grade7_molecules_v1',JSON.stringify(['H2O','CO2']));
storage.set('hh60s_grade7_games_v1',JSON.stringify({memory:32}));
const activities=api.activities();
assert.equal(activities.filter(x=>x.completedAt).length,2);
assert.ok(activities.filter(x=>!x.completedAt).length>=4);
assert.ok(activities.filter(x=>!x.completedAt).every(x=>x.eventId.startsWith('legacy:')));
assert.equal(activities.find(x=>x.activityId==='H2O').completedAt,null);
const backup=api.exportData();assert.equal(backup.app,'ptw-lab-progress');assert.equal(backup.schemaVersion,1);assert.equal(backup.events.length,activities.length);
assert.equal(api.importData(backup),backup.events.length);
assert.equal(api.read().filter(x=>x.completedAt===null).length,backup.events.length-2);
assert.throws(()=>api.importData({...backup,schemaVersion:2}));
api.reset();assert.equal(api.activities().length,0);
console.log('PASS lab progress events, dedupe, undated legacy, backup/import and reset');
