'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const index = JSON.parse(fs.readFileSync(path.join(root, 'data/exams.json'), 'utf8'));
const registry = {};
for (const entry of index.exams) {
  if (entry.hidden || entry.demo || entry.customUrl) continue;
  if (!/^[\w-]+$/.test(entry.id)) throw Error('Invalid exam ID');
  const exam = JSON.parse(fs.readFileSync(path.join(root, 'data/tests', entry.id + '.json'), 'utf8'));
  if (exam.demo || exam.id !== entry.id) throw Error('Exam identity mismatch: ' + entry.id);
  const questions = exam.questions.map(q => {
    if (q.part === 1 && Number.isInteger(q.answerIndex) && q.answerIndex >= 0 && q.answerIndex < q.options.length) return { part: 1, answerIndex: q.answerIndex, optionCount: q.options.length };
    if (q.part === 2 && q.statements.length >= 1 && q.statements.length <= 4 && q.statements.every(s => typeof s.answer === 'boolean')) return { part: 2, statements: q.statements.map(s => ({ answer: s.answer })) };
    if (q.part === 3 && typeof q.answer === 'number' && Number.isFinite(q.answer) && (q.tolerance == null || Number.isFinite(q.tolerance) && q.tolerance >= 0)) return { part: 3, answer: q.answer, tolerance: q.tolerance || 0 };
    throw Error('Unscorable question in ' + entry.id);
  });
  registry[entry.id] = {
    revision: crypto.createHash('sha256').update(JSON.stringify(exam)).digest('hex'),
    title: exam.title, code: entry.code ?? exam.code ?? '',
    openAt: entry.openAt ?? exam.openAt ?? '', closeAt: entry.closeAt ?? exam.closeAt ?? '',
    maxAttempts: entry.maxAttempts ?? exam.maxAttempts ?? 0,
    scoring: exam.scoring || {}, questions
  };
}
const output = '// Generated by node scripts/build_exam_registry.cjs. Deploy with Code.gs.\nconst SERVER_EXAMS = ' + JSON.stringify(registry) + ';\n';
const destination = path.join(root, 'apps-script/ExamRegistry.gs');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) throw Error('Exam registry stale: run node scripts/build_exam_registry.cjs');
} else fs.writeFileSync(destination, output);
console.log('Exam registry: ' + Object.keys(registry).length + ' published exams' + (process.argv.includes('--check') ? ' verified' : ' generated'));
